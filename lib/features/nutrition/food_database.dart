/// Substring search over names, ranked so a prefix match beats a mid-word one.
///
/// Deliberately not fuzzy — a typo-tolerant matcher that silently logs "dal
/// makhani" when the user typed "dal makhni" is fine, but one that logs
/// "cheeseburger" for "chana" is not.
List<FoodDefinition> searchFoods(String query, {int limit = 20}) {
  final needle = query.trim().toLowerCase();
  if (needle.isEmpty) return const [];

  final scored = <({FoodDefinition item, int score})>[];
  for (final item in foodDatabase) {
    final index = item.name.toLowerCase().indexOf(needle);
    if (index == -1) continue;
    scored.add((item: item, score: index == 0 ? 0 : 1 + index));
  }

  scored.sort((a, b) {
    final byScore = a.score.compareTo(b.score);
    return byScore != 0 ? byScore : a.item.name.compareTo(b.item.name);
  });

  return scored.take(limit).map((e) => e.item).toList();
}

List<FoodDefinition> foodsByTag(FoodTag tag) =>
    foodDatabase.where((item) => item.tags.contains(tag)).toList();

/// Dishes plausible at a restaurant of this cuisine.
///
/// An unknown cuisine gets the pan-cuisine staples rather than nothing — a
/// "restaurant" with no type tags still serves grilled chicken and salad.
List<FoodDefinition> menuForCuisine(Cuisine? cuisine) =>
    foodDatabase.where((food) => food.cuisine == cuisine).toList();
